// The wave picture, given. It draws the wave shape that the select pins choose, as a picture
// on the VGA screen: a sine, a saw, a triangle or a square, two cycles in a box. It is a picture
// of the CHOICE, not of the data: the shape does not depend on the frequency or the amplitude, or
// on anything your core does, so it is there even before your core works.
//   sel 0 sine    sel 1 saw    sel 2 triangle    sel 3 square      (the same order as the core)
// Two modules:
//   vga_wave_value  the height, 0 to 255, of one cycle of the chosen wave at a position 0 to 127.
//   vga_wave_shape  draws it. A pixel is lit when the wave passes through it, and the pixels
//                   between this column and the one before are lit too, so a square wave has
//                   its vertical edges.
// You do not edit this file.
`default_nettype none

module vga_wave_value (
    input  wire [1:0] sel,
    input  wire [6:0] pos,     // where in one cycle, 0 to 127
    output reg  [7:0] value    // how high the wave is there, 0 to 255
);
    // A quarter of a sine, 33 steps from 0 up to 127 (127 times sin of the angle).
    reg  [6:0] s;
    wire [5:0] index = pos[5] ? (6'd32 - {1'b0, pos[4:0]}) : {1'b0, pos[4:0]};
    always @(*) begin
        case (index)
            6'd0: s = 7'd0;
            6'd1: s = 7'd6;
            6'd2: s = 7'd12;
            6'd3: s = 7'd19;
            6'd4: s = 7'd25;
            6'd5: s = 7'd31;
            6'd6: s = 7'd37;
            6'd7: s = 7'd43;
            6'd8: s = 7'd49;
            6'd9: s = 7'd54;
            6'd10: s = 7'd60;
            6'd11: s = 7'd65;
            6'd12: s = 7'd71;
            6'd13: s = 7'd76;
            6'd14: s = 7'd81;
            6'd15: s = 7'd85;
            6'd16: s = 7'd90;
            6'd17: s = 7'd94;
            6'd18: s = 7'd98;
            6'd19: s = 7'd102;
            6'd20: s = 7'd106;
            6'd21: s = 7'd109;
            6'd22: s = 7'd112;
            6'd23: s = 7'd115;
            6'd24: s = 7'd117;
            6'd25: s = 7'd120;
            6'd26: s = 7'd122;
            6'd27: s = 7'd123;
            6'd28: s = 7'd125;
            6'd29: s = 7'd126;
            6'd30: s = 7'd126;
            6'd31: s = 7'd127;
            6'd32: s = 7'd127;
            default: s = 7'd0;
        endcase
    end

    // The sine is 128 plus the quarter in the first half and 128 minus it in the second.
    wire [7:0] sine = pos[6] ? (8'd128 - {1'b0, s}) : (8'd128 + {1'b0, s});

    always @(*) begin
        case (sel)
            2'd0:    value = sine;
            2'd1:    value = {pos, 1'b0};                                      // saw
            2'd2:    value = pos[6] ? {~pos[5:0], 2'b00} : {pos[5:0], 2'b00};    // triangle
            default: value = pos[6] ? 8'hFF : 8'h00;                             // square
        endcase
    end
endmodule

module vga_wave_shape (
    input  wire [9:0] x,
    input  wire [9:0] y,
    input  wire       active,
    input  wire [1:0] sel,
    output wire [5:0] rgb       // {R[1:0], G[1:0], B[1:0]}
);
    // The wave is 256 wide and 256 high, in the middle of the screen: columns 192 to 447, rows
    // 112 to 367. Two cycles of 128 columns each. The frame sits 8 pixels outside it, so the
    // top and bottom of a square wave are not hidden by the frame.
    wire in_box = active && (x >= 10'd192) && (x < 10'd448) && (y >= 10'd112) && (y < 10'd368);
    wire in_pad = active && (x >= 10'd184) && (x < 10'd456) && (y >= 10'd104) && (y < 10'd376);

    // This column's position in the cycle, and the one before it.
    wire [6:0] pos      = x[6:0] + 7'd64;
    wire [6:0] pos_back = pos - 7'd1;

    wire [7:0] here;
    wire [7:0] previous;
    vga_wave_value now_value  (.sel(sel), .pos(pos),      .value(here));
    vga_wave_value back_value (.sel(sel), .pos(pos_back), .value(previous));

    // How high this row is, 255 at the top of the box and 0 at the bottom.
    wire [7:0] height = 8'd255 - (y[7:0] - 8'd112);

    wire [7:0] low  = (here < previous) ? here : previous;
    wire [7:0] high = (here < previous) ? previous : here;

    // Lit when the row is between this column's value and the previous one's, a pixel either
    // side so the line is three pixels thick.
    wire lit      = in_box && ({1'b0, height} + 9'd1 >= {1'b0, low}) && ({1'b0, height} <= {1'b0, high} + 9'd1);
    wire midline  = in_pad && (height == 8'd128);
    wire frame    = active && (x >= 10'd183) && (x <= 10'd456) && (y >= 10'd103) && (y <= 10'd376) && !in_pad;

    //            green           grey            grey          dark blue
    assign rgb = lit ? 6'b001100 : (midline || frame) ? 6'b010101 : active ? 6'b000001 : 6'b000000;
endmodule
